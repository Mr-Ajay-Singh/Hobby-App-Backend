/**
 * GET /api/v1/ai/chat-history
 * GET /api/v1/ai/conversations/:conversationId/messages
 * Query params: page=1&limit=20&userId=...
 */
exports.getConversationMessages = async (req, res) => {
    try {
        let conversationId = req.params.conversationId || req.query.conversationId
        const userHobbyId = req.query.userHobbyId
        const userId = req.userId || req.user?._id || req.user?.uid || req.query?.userId || req.body?.userId
        const page = Math.max(1, parseInt(req.query.page) || 1)
        const limit = Math.min(50, Math.max(1, parseInt(req.query.limit) || 20))

        let conversation = null
        if (conversationId && conversationId !== 'current') {
            // A supplied conversation must belong to the current user.
            conversation = await Conversation.findOne({ _id: conversationId, userId })
        } else if (userHobbyId) {
            // Find the user's most recently active conversation for this specific userHobbyId
            conversation = await Conversation.findOne({ userId, userHobbyId }).sort({ lastMessageAt: -1, updatedAt: -1 })
        } else {
            // Find the user's most recently active conversation across any hobby
            conversation = await Conversation.findOne({ userId }).sort({ lastMessageAt: -1, updatedAt: -1 })
        }

        if (!conversation) {
            return sendResponse(res, 200, {
                success: true,
                conversationId: null,
                page: 1,
                limit,
                totalMessages: 0,
                totalPages: 0,
                hasMore: false,
                messages: []
            })
        }

        conversationId = conversation._id

        const totalMessages = await Message.countDocuments({ conversationId })
        const totalPages = Math.ceil(totalMessages / limit)
        const skip = (page - 1) * limit

        // Page 1 is the latest chat page. Reverse it before returning so the UI
        // still receives messages in natural oldest-to-newest display order.
        const rawMessages = await Message.find({ conversationId })
            .sort({ createdAt: -1, _id: -1 })
            .skip(skip)
            .limit(limit)
            .lean()

        rawMessages.reverse()

        let skillInfo = null
        const effectiveUserHobbyId = conversation.userHobbyId || userHobbyId
        if (effectiveUserHobbyId) {
            const userHobby = await UserHobby.findById(effectiveUserHobbyId).populate('hobbyId', 'name').lean()
            if (userHobby) {
                const userSkill = await UserSkill.findOne({ userHobbyId: effectiveUserHobbyId }).lean()
                skillInfo = {
                    skillName: userHobby.hobbyId?.name || 'Skill',
                    currentLevel: userSkill?.level || 'beginner',
                    score: userSkill?.score || 0
                }
            }
        }

        const formattedMessages = rawMessages.map(msg => {
            let parsedContent = null
            if (msg.role === 'assistant' && msg.content) {
                try {
                    parsedContent = JSON.parse(msg.content)
                    if (parsedContent?.learningContent) {
                        const lc = parsedContent.learningContent
                        if (lc.flashcard && !lc.flashcards) lc.flashcards = lc.flashcard
                        else if (lc.flashcards && !lc.flashcard) lc.flashcard = lc.flashcards
                    }
                } catch (e) {
                    parsedContent = { text: msg.content }
                }
            }

            return {
                id: msg._id,
                conversationId: msg.conversationId,
                role: msg.role,
                content: msg.content,
                parsedContent,
                contentType: msg.contentType,
                assetIds: msg.assetIds || [],
                createdAt: msg.createdAt
            }
        })

        return sendResponse(res, 200, {
            success: true,
            conversationId,
            skillInfo,
            page,
            limit,
            totalMessages,
            totalPages,
            hasMore: page < totalPages,
            messages: formattedMessages
        })

    } catch (err) {
        console.error('[SkillLearning] Error in getConversationMessages:', err)
        return sendResponse(res, 500, { info: `Failed to fetch conversation history: ${err.message}` }, err)
    }
}

/**
 * POST /api/v1/ai/submit-quiz
 * Evaluates a learner's quiz answer, deduplicates attempts, enforces 20 XP daily cap, and awards +2 XP.
 */
exports.submitQuizAnswer = async (req, res) => {
    try {
        const userId = req.userId || req.user?._id || req.user?.uid || req.query?.userId || req.body?.userId
        const { userHobbyId, hobbySkillId, quizId, questionIndex, selectedIndex, correctIndex } = req.body

        if (!userHobbyId || !quizId || questionIndex === undefined || selectedIndex === undefined || correctIndex === undefined) {
            return sendResponse(res, 400, { success: false, message: 'Missing required quiz submission fields.' })
        }

        const isCorrect = Number(selectedIndex) === Number(correctIndex)
        const QuizAttempt = require('../Models/QuizAttempt')
        const UserSkill = require('../Models/UserSkill')

        // 1. Prevent duplicate XP for the same question
        const existingAttempt = await QuizAttempt.findOne({ userId, quizId, questionIndex })
        if (existingAttempt) {
            return sendResponse(res, 200, {
                success: true,
                message: 'Question already evaluated.',
                isCorrect: existingAttempt.isCorrect,
                xpAwarded: 0,
                alreadyAnswered: true
            })
        }

        let userSkill = null
        if (hobbySkillId) {
            userSkill = await UserSkill.findOne({ userHobbyId, hobbySkillId })
        } else {
            userSkill = await UserSkill.findOne({ userHobbyId }).sort({ updatedAt: -1 })
        }

        // 2. Daily Cap Pacing Logic (20 XP max per calendar day)
        const todayStr = new Date().toISOString().split('T')[0]
        const lastDateStr = userSkill?.lastXpDate ? new Date(userSkill.lastXpDate).toISOString().split('T')[0] : ''

        let dailyXp = userSkill?.dailyXpEarned || 0
        if (lastDateStr !== todayStr) {
            dailyXp = 0 // Reset daily counter for a new calendar day
        }

        const DAILY_CAP = 20
        let xpToAward = 0

        if (isCorrect) {
            const baseXP = 2 // +2 XP per correct quiz answer
            const remainingCap = Math.max(0, DAILY_CAP - dailyXp)
            xpToAward = Math.min(baseXP, remainingCap)
        }

        // 3. Save Quiz Attempt Record
        await QuizAttempt.create({
            userId,
            userHobbyId,
            hobbySkillId: userSkill?.hobbySkillId || userHobbyId,
            quizId,
            questionIndex,
            selectedIndex,
            correctIndex,
            isCorrect,
            xpAwarded: xpToAward
        })

        // 4. Update UserSkill Score & Level
        let newScore = userSkill?.score || 0
        let newLevel = userSkill?.level || SKILL_LEVEL.BEGINNER

        if (userSkill && xpToAward > 0) {
            newScore = Math.min(100, (userSkill.score || 0) + xpToAward)
            userSkill.score = newScore
            userSkill.dailyXpEarned = dailyXp + xpToAward
            userSkill.lastXpDate = new Date()

            if (newScore >= 76) newLevel = SKILL_LEVEL.EXPERT
            else if (newScore >= 51) newLevel = SKILL_LEVEL.ADVANCED
            else if (newScore >= 26) newLevel = SKILL_LEVEL.INTERMEDIATE
            else newLevel = SKILL_LEVEL.BEGINNER

            userSkill.level = newLevel
            await userSkill.save()

            // Invalidate leaderboard cache so next fetch gets updated scores
            try {
                const { invalidateLeaderboardCache } = require('./leaderboardController')
                invalidateLeaderboardCache()
            } catch (e) {
                // Ignore cache invalidation error
            }
        }

        // Record Practice Session (+1 min credit for quiz attempt)
        await recordLearningPracticeSession({
            userId,
            userHobbyId,
            quizCount: 1,
            topicTitle: 'Quiz Practice Drill',
            explicitSeconds: 60
        }).catch(() => {})

        return sendResponse(res, 200, {
            success: true,
            isCorrect,
            xpAwarded: xpToAward,
            newScore,
            newLevel,
            dailyXpEarned: dailyXp + xpToAward,
            isCapReached: (dailyXp + xpToAward) >= DAILY_CAP
        })
    } catch (err) {
        console.error('[SkillLearning] Error in submitQuizAnswer:', err)
        return sendResponse(res, 500, { success: false, message: 'Failed to submit quiz answer.', error: err.message })
    }
}

