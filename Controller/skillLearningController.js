// ─── Helpers: SVG Formatting ───────────────────────────────────────────────────

function escapeSvgText(value) {
    return String(value || '').replace(/[&<>'"]/g, character => ({
        '&': '&amp;',
        '<': '&lt;',
        '>': '&gt;',
        "'": '&apos;',
        '"': '&quot;'
    }[character]))
}

function getFallbackSvg(title = 'Skill Diagram') {
    const safeTitle = escapeSvgText(title)
    return `<svg width="400" height="150" viewBox="0 0 400 150" xmlns="http://www.w3.org/2000/svg" role="img" aria-label="${safeTitle}">
  <title>${safeTitle}</title>
  <rect width="100%" height="100%" fill="#1e1e2e" rx="10"/>
  <text x="50%" y="40%" dominant-baseline="middle" text-anchor="middle" fill="#cba6f7" font-family="sans-serif" font-size="18" font-weight="bold">${safeTitle}</text>
  <text x="50%" y="65%" dominant-baseline="middle" text-anchor="middle" fill="#a6adc8" font-family="sans-serif" font-size="13">Visual guide generated for your practice session</text>
</svg>`
}

function cleanSvg(svgString, fallbackTitle = 'Skill Visual') {
    if (!svgString || typeof svgString !== 'string') {
        return getFallbackSvg(fallbackTitle)
    }

    let cleaned = svgString.trim()
    if (cleaned.includes('```xml')) {
        cleaned = cleaned.replace(/^```xml\s*/i, '').replace(/\s*```$/, '').trim()
    } else if (cleaned.includes('```svg')) {
        cleaned = cleaned.replace(/^```svg\s*/i, '').replace(/\s*```$/, '').trim()
    } else if (cleaned.includes('```')) {
        cleaned = cleaned.replace(/^```\s*/, '').replace(/\s*```$/, '').trim()
    }

    const svgMatch = cleaned.match(/<svg\b[^>]*>[\s\S]*<\/svg>/i)
    if (!svgMatch) return getFallbackSvg(fallbackTitle)

    cleaned = svgMatch[0].trim()
    const rootTag = cleaned.match(/^<svg\b[^>]*>/i)?.[0]
    const containsUnsafeContent = /<(?:script|foreignObject|iframe|object|embed|image|audio|video|style)\b|\son[a-z]+\s*=|\b(?:href|xlink:href)\s*=\s*(['"]?)\s*(?:https?:|\/\/|data:|javascript:)|url\s*\(\s*['"]?\s*(?:https?:|\/\/|data:|javascript:)/i.test(cleaned)

    if (!rootTag || !/\bviewBox\s*=/i.test(rootTag) || containsUnsafeContent) {
        console.warn('[SkillLearning] Rejected unsafe or incomplete SVG generated by AI.')
        return getFallbackSvg(fallbackTitle)
    }

    const safeTitle = escapeSvgText(fallbackTitle)
    cleaned = cleaned.replace(/^<svg\b([^>]*)>/i, (match, attributes) => {
        let safeAttributes = attributes
        if (!/\bxmlns\s*=/i.test(safeAttributes)) safeAttributes += ' xmlns="http://www.w3.org/2000/svg"'
        if (!/\brole\s*=/i.test(safeAttributes)) safeAttributes += ' role="img"'
        if (!/\baria-label\s*=/i.test(safeAttributes)) safeAttributes += ` aria-label="${safeTitle}"`
        return `<svg${safeAttributes}>`
    })

    if (!/<title\b/i.test(cleaned)) {
        cleaned = cleaned.replace(/^(<svg\b[^>]*>)/i, `$1<title>${safeTitle}</title>`)
    }

    return cleaned
}

// ─── Individual Form Processing Handlers ────────────────────────────────────────

function processTextForm(learningContent) {
    return learningContent.text || 'Here is your lesson for today.'
}

async function processSvgForm(learningContent, hobbySkill, userId, userHobbyId, assetIds) {
    if (!learningContent.svg) return null
    const validSvg = cleanSvg(learningContent.svg, hobbySkill?.name || 'Skill Visual')
    const svgAsset = await UserAsset.create({
        userId,
        userHobbyId,
        type: 'image',
        mimeType: 'image/svg+xml',
        purpose: USER_ASSET_PURPOSE.LEARNING_DIAGRAM,
        metadata: { svg: validSvg }
    })
    assetIds.push(svgAsset._id)
    return validSvg
}



function processQuizForm(learningContent) {
    if (!Array.isArray(learningContent.quiz) || learningContent.quiz.length === 0) return null
    return learningContent.quiz.map((q, idx) => ({
        id: q.id || `q_${idx + 1}`,
        question: q.question || 'Knowledge check question:',
        options: Array.isArray(q.options) ? q.options : [],
        correctIndex: typeof q.correctIndex === 'number' ? q.correctIndex : 0,
        explanation: q.explanation || ''
    }))
}

function processFlashcardsForm(learningContent) {
    const cards = learningContent.flashcards || learningContent.flashcard
    if (!Array.isArray(cards) || cards.length === 0) return null
    return cards.map(card => ({
        front: card.front || '',
        back: card.back || ''
    }))
}

function processMusicalNotesForm(learningContent) {
    if (!learningContent.musicalNotes || typeof learningContent.musicalNotes !== 'object') return null
    const mn = learningContent.musicalNotes
    return {
        instrument: mn.instrument || 'piano',
        bpm: Number.isFinite(mn.bpm) ? Math.max(20, Math.min(300, mn.bpm)) : 80,
        notes: Array.isArray(mn.notes)
            ? mn.notes.map(note => ({
                pitch: typeof note?.pitch === 'string' ? note.pitch : '',
                startBeat: Number.isFinite(note?.startBeat) ? Math.max(0, note.startBeat) : 0,
                durationBeats: Number.isFinite(note?.durationBeats) ? Math.max(0.125, note.durationBeats) : 1,
                velocity: Number.isFinite(note?.velocity) ? Math.max(0, Math.min(127, note.velocity)) : 80,
                finger: Number.isInteger(note?.finger) && note.finger >= 1 && note.finger <= 5 ? note.finger : null
            }))
            : []
    }
}

function processChecklistForm(learningContent) {
    if (!Array.isArray(learningContent.checklist) || learningContent.checklist.length === 0) return null
    return learningContent.checklist.map((item, idx) => ({
        step: item.step || idx + 1,
        title: item.title || `Step ${idx + 1}`,
        instruction: item.instruction || ''
    }))
}

function processVideoForm(learningContent) {
    if (!learningContent.video || typeof learningContent.video !== 'object') return null
    const v = learningContent.video
    return {
        title: v.title || 'Demonstration Video',
        embedUrl: v.embedUrl || '',
        startTimeSeconds: v.startTimeSeconds || 0,
        durationSeconds: v.durationSeconds || 30
    }
}

function processCodeSnippetForm(learningContent) {
    if (!learningContent.codeSnippet || typeof learningContent.codeSnippet !== 'object') return null
    const cs = learningContent.codeSnippet
    return {
        language: cs.language || 'python',
        code: cs.code || '',
        expectedOutput: cs.expectedOutput || ''
    }
}

// ─── Helper: AI-Driven Hobby & Skill Curriculum Generator ───────────────────────

async function detectAndCreateHobbyWithAi(userMessage, userId, modelChoice = 'gemini') {
    const aiSystemInstruction = `You are a Hobby & Skill Curriculum AI Architect.
Analyze the user's message and determine if the user is asking to learn a specific hobby or skill (e.g. Piano, Guitar, Sourdough Baking, Chess, Origami, Archery, French Cooking, Python Coding, Calligraphy, Skateboarding, Martial Arts, Songwriting).

If a specific hobby/skill is detected:
Return JSON:
{
  "isHobbyDetected": true,
  "hobbyName": "Proper Title Case Name",
  "slug": "url-friendly-slug",
  "category": "Broad Category (e.g. Music, Cooking, Sports, Creative, Gaming, Tech)",
  "description": "Brief 1-sentence description of the hobby.",
  "initialSkills": [
    {
      "name": "Skill Name 1",
      "slug": "skill-slug-1",
      "category": "Category",
      "skillType": "knowledge | physical | creative | technical | strategic",
      "description": "Short description"
    },
    {
      "name": "Skill Name 2",
      "slug": "skill-slug-2",
      "category": "Category",
      "skillType": "knowledge | physical | creative | technical | strategic",
      "description": "Short description"
    }
  ]
}

If NO specific hobby/skill is mentioned (e.g. "Hi", "Teach me something", "Hello", vague prompt):
Return JSON:
{
  "isHobbyDetected": false
}`

    try {
        const aiRes = await generateStructuredContent({
            model: modelChoice,
            systemInstruction: aiSystemInstruction,
            messages: [{ role: 'user', content: userMessage }],
            temperature: 0.2
        })

        if (!aiRes || !aiRes.isHobbyDetected || !aiRes.hobbyName) {
            return null
        }

        const slug = aiRes.slug || aiRes.hobbyName.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '')

        let hobby = await Hobby.findOne({ slug })
        if (!hobby) {
            hobby = await Hobby.create({
                name: aiRes.hobbyName,
                slug,
                category: aiRes.category || 'General',
                description: aiRes.description || `Learning ${aiRes.hobbyName}`,
                capabilities: ['text', 'audio', 'svg_generation']
            })
        }

        if (Array.isArray(aiRes.initialSkills) && aiRes.initialSkills.length > 0) {
            for (const skillData of aiRes.initialSkills) {
                const skillSlug = skillData.slug || skillData.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '')
                const existingSkill = await HobbySkill.findOne({ hobbyId: hobby._id, slug: skillSlug })
                if (!existingSkill) {
                    await HobbySkill.create({
                        hobbyId: hobby._id,
                        name: skillData.name,
                        slug: skillSlug,
                        category: skillData.category || hobby.category,
                        skillType: ['knowledge', 'physical', 'creative', 'technical', 'strategic'].includes(skillData.skillType) ? skillData.skillType : 'technical',
                        description: skillData.description || '',
                        assessmentMethods: ['text'],
                        isActive: true
                    })
                }
            }
        }

        const userHobby = await UserHobby.create({
            userId,
            hobbyId: hobby._id,
            currentStage: 'active_learning',
            status: 'active'
        })

        return userHobby

    } catch (err) {
        console.error('[SkillLearning] Error detecting hobby via AI:', err.message)
        return null
    }
}

// ─── Step 1: Resolve UserHobby & Conversation Context ─────────────────────────

async function resolveUserHobbyAndConversation({ userId, conversationId, reqUserHobbyId, message, modelChoice }) {
    let conversation = null
    if (conversationId) {
        conversation = await Conversation.findById(conversationId)
    }

    let userHobby = null
    if (conversation && conversation.userHobbyId) {
        userHobby = await UserHobby.findById(conversation.userHobbyId)
    }
    if (!userHobby && reqUserHobbyId) {
        userHobby = await UserHobby.findById(reqUserHobbyId)
    }
    if (!userHobby) {
        userHobby = await UserHobby.findOne({ userId, status: 'active' })
    }

    if (!userHobby) {
        userHobby = await detectAndCreateHobbyWithAi(message, userId, modelChoice)
    }

    if (!userHobby) {
        const tempTitle = message.trim().slice(0, 35) + '...'
        const clarificationText = 'Welcome! Which hobby or skill would you like to learn today? (For example: Piano, Guitar, Sourdough Baking, Chess, Drawing, Songwriting, Cooking)'

        let pendingConversation = conversation
        if (!pendingConversation) {
            const placeholderHobby = await Hobby.findOneAndUpdate(
                { slug: 'general-learning' },
                { name: 'General Learning', slug: 'general-learning', capabilities: ['text', 'audio', 'svg_generation'] },
                { upsert: true, new: true }
            )
            userHobby = await UserHobby.create({
                userId,
                hobbyId: placeholderHobby._id,
                currentStage: 'onboarding',
                status: 'active'
            })
            pendingConversation = await Conversation.create({
                userId,
                userHobbyId: userHobby._id,
                title: tempTitle,
                messageCount: 0
            })
        }

        const assistantMsgDoc = await Message.create({
            conversationId: pendingConversation._id,
            role: 'assistant',
            content: clarificationText,
            contentType: 'text'
        })

        return {
            needsOnboardingClarification: true,
            clarificationResponse: {
                success: true,
                conversationId: pendingConversation._id,
                messageId: assistantMsgDoc._id,
                responseType: RESPONSE_TYPE.CLARIFICATION,
                skillInfo: {
                    skillName: 'Onboarding',
                    currentLevel: SKILL_LEVEL.BEGINNER,
                    score: 0
                },
                learningContent: {
                    formsDelivered: ['text'],
                    text: clarificationText
                }
            }
        }
    }

    if (!conversation) {
        conversation = await Conversation.create({
            userId,
            userHobbyId: userHobby._id,
            title: message.trim().slice(0, 35) + '...',
            messageCount: 0
        })
    }

    return { conversation, userHobby, needsOnboardingClarification: false }
}

// ─── Step 2: Resolve Skill Metadata & User Progress ───────────────────────────

const SKILL_MATCH_STOP_WORDS = new Set([
    'about', 'again', 'also', 'and', 'are', 'can', 'could', 'does', 'explain', 'for',
    'from', 'have', 'help', 'how', 'into', 'learn', 'lesson', 'like', 'more', 'need',
    'please', 'show', 'skill', 'teach', 'that', 'the', 'this', 'want', 'what', 'with', 'you', 'your'
])

function getMeaningfulWords(value = '') {
    return new Set(
        String(value)
            .toLowerCase()
            .match(/[a-z0-9]+/g)
            ?.filter(word => word.length >= 3 && !SKILL_MATCH_STOP_WORDS.has(word)) || []
    )
}

function findSkillMatchingMessage(skills = [], message = '') {
    const messageWords = getMeaningfulWords(message)
    if (messageWords.size === 0) return null

    let bestSkill = null
    let bestScore = 0

    for (const skill of skills) {
        const nameWords = getMeaningfulWords(skill.name)
        const detailWords = getMeaningfulWords(`${skill.category || ''} ${skill.description || ''}`)
        let score = 0

        for (const word of messageWords) {
            if (nameWords.has(word)) score += 3
            else if (detailWords.has(word)) score += 1
        }

        if (score > bestScore) {
            bestScore = score
            bestSkill = skill
        }
    }

    return bestSkill
}

async function resolveSkillMetadataAndProgress({ userHobbyId, reqHobbySkillId, message = '' }) {
    let hobbySkillId = reqHobbySkillId || null
    let hobbySkill = null
    const userHobby = await UserHobby.findById(userHobbyId).populate('hobbyId')

    if (hobbySkillId) {
        hobbySkill = await HobbySkill.findById(hobbySkillId)
    }

    if (!hobbySkill && userHobby) {
        const targetHobbyId = userHobby.hobbyId?._id || userHobby.hobbyId
        const activeSkills = await HobbySkill.find({ hobbyId: targetHobbyId, isActive: true })
            .sort({ createdAt: 1 })
        hobbySkill = findSkillMatchingMessage(activeSkills, message) || activeSkills[0] || null

        if (!hobbySkill && targetHobbyId) {
            const hobbyName = userHobby.hobbyId?.name || 'Skill'
            const slug = (userHobby.hobbyId?.slug || 'hobby') + '-fundamentals'
            hobbySkill = await HobbySkill.findOne({ slug })
            if (!hobbySkill) {
                hobbySkill = await HobbySkill.create({
                    hobbyId: targetHobbyId,
                    name: `${hobbyName} Fundamentals`,
                    slug,
                    category: userHobby.hobbyId?.category || 'General',
                    skillType: 'knowledge',
                    description: `Core concepts and fundamentals for ${hobbyName}`,
                    isActive: true
                })
            }
        }
    }

    if (hobbySkill) {
        hobbySkillId = hobbySkill._id
    }

    let userSkill = null
    if (hobbySkillId) {
        userSkill = await UserSkill.findOne({ userHobbyId, hobbySkillId })
    }

    const currentLevel = userSkill?.level || SKILL_LEVEL.BEGINNER
    const currentScore = userSkill?.score ?? 0
    const strengths = userSkill?.strengths || []
    const weaknesses = userSkill?.weaknesses || []

    return {
        hobbySkill,
        userSkill,
        currentLevel,
        currentScore,
        strengths,
        weaknesses
    }
}

// ─── Helper: Update User Progress & Calculate Level ───────────────────────────

async function updateUserSkillProgress({ userId, userHobbyId, hobbySkill, userSkill, evalData = {} }) {
    if (!hobbySkill) return { currentLevel: SKILL_LEVEL.BEGINNER, currentScore: 0 }

    if (!userSkill) {
        userSkill = await UserSkill.findOne({ userHobbyId, hobbySkillId: hobbySkill._id })
    }

    const currentScore = userSkill?.score ?? 0
    // Default scoreDelta is 0 for regular chat messages (XP is earned strictly from quizzes & task completions!)
    const scoreDelta = typeof evalData.scoreDelta === 'number' ? evalData.scoreDelta : 0
    let newScore = Math.max(0, Math.min(100, currentScore + scoreDelta))

    let newLevel = SKILL_LEVEL.BEGINNER
    if (newScore >= 76) newLevel = SKILL_LEVEL.EXPERT
    else if (newScore >= 51) newLevel = SKILL_LEVEL.ADVANCED
    else if (newScore >= 26) newLevel = SKILL_LEVEL.INTERMEDIATE

    const newStrengths = Array.isArray(evalData.newStrengths) ? evalData.newStrengths : []
    const newWeaknesses = Array.isArray(evalData.newWeaknesses) ? evalData.newWeaknesses : []

    const updatedStrengths = Array.from(new Set([...(userSkill?.strengths || []), ...newStrengths]))
    const updatedWeaknesses = Array.from(new Set([...(userSkill?.weaknesses || []), ...newWeaknesses]))

    if (!userSkill) {
        userSkill = await UserSkill.create({
            userId,
            userHobbyId,
            hobbySkillId: hobbySkill._id,
            score: newScore,
            level: newLevel,
            strengths: updatedStrengths,
            weaknesses: updatedWeaknesses,
            lastPracticedAt: new Date()
        })
    } else {
        userSkill.score = newScore
        userSkill.level = newLevel
        userSkill.strengths = updatedStrengths
        userSkill.weaknesses = updatedWeaknesses
        userSkill.lastPracticedAt = new Date()
        await userSkill.save()
    }

    return {
        currentLevel: newLevel,
        currentScore: newScore,
        userSkill
    }
}

// ─── Helper: Record & Coalesce Practice Sessions ──────────────────────────────

async function recordLearningPracticeSession({
    userId,
    userHobbyId,
    lessonText = '',
    formsDelivered = [],
    quizCount = 0,
    topicTitle = 'AI Learning Session',
    explicitSeconds = null
}) {
    if (!userHobbyId) return null

    let durationSeconds = 0
    if (typeof explicitSeconds === 'number' && explicitSeconds > 0) {
        durationSeconds = Math.round(explicitSeconds)
    } else {
        const wordCount = (lessonText || '').split(/\s+/).filter(Boolean).length
        durationSeconds = Math.max(60, Math.round(wordCount * 0.3 + 30))

        if (formsDelivered.includes('svg')) durationSeconds += 60
        if (formsDelivered.includes('checklist')) durationSeconds += 60
        if (formsDelivered.includes('musical_notes')) durationSeconds += 90
        if (formsDelivered.includes('code_snippet')) durationSeconds += 90
        if (quizCount > 0) durationSeconds += (quizCount * 60)
    }

    try {
        const fifteenMinsAgo = new Date(Date.now() - 15 * 60 * 1000)
        let session = await PracticeSession.findOne({
            userHobbyId,
            status: 'completed',
            createdAt: { $gte: fifteenMinsAgo }
        }).sort({ createdAt: -1 })

        if (session) {
            session.durationSeconds = (session.durationSeconds || 0) + durationSeconds
            await session.save()
            return session
        }

        return await PracticeSession.create({
            userId,
            userHobbyId,
            title: topicTitle,
            durationSeconds,
            status: 'completed',
            score: 100
        })
    } catch (err) {
        console.error('[SkillLearning] Error recording PracticeSession:', err.message)
        return null
    }
}


